// Rebuilds catalog.js from tools/meta.json (the master list of games).
// meta.json: array of {slug,title,category,tags,blurb,controls,prompt,added,external?}
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const meta = JSON.parse(fs.readFileSync(path.join(__dirname, 'meta.json'), 'utf8'));
const seen = new Set();
const out = [];
for (const m of meta) {
  if (seen.has(m.slug)) throw new Error('duplicate slug ' + m.slug);
  seen.add(m.slug);
  if (!fs.existsSync(path.join(root, 'games', m.slug + '.html'))) { console.warn('skip (no file): ' + m.slug); continue; }
  if (!fs.existsSync(path.join(root, 'thumbs', m.slug + '.jpg'))) console.warn('missing thumb: ' + m.slug);
  const { prompt, ...pub } = m;
  out.push({ ...pub, file: 'games/' + m.slug + '.html', thumb: 'thumbs/' + m.slug + '.jpg' });
}
fs.writeFileSync(path.join(root, 'catalog.js'), '// Generated by build/build-catalog.js\nwindow.GAMEBOP_GAMES = ' + JSON.stringify(out, null, 1) + ';\n');
console.log('catalog.js: ' + out.length + ' games');
